import { expect, it } from "vitest";
import { ProfileSchema, testProfile } from "../../src/core/config";
import {
	classifyRipples,
	DEFAULT_TEST_GLOBS,
	rippleClassifier,
} from "../../src/core/ripple";

const defaults = { tests: [...DEFAULT_TEST_GLOBS], generated: [] };

it("classifies specs, fixtures and test setup as test under the default globs", () => {
	const kind = rippleClassifier(defaults);
	for (const f of [
		"packages/acme-web/src/invoices/total.test.ts",
		"packages/acme-web/src/invoices/total.spec.tsx",
		"packages/acme-web/src/chat/live-chat-menu.itest.ts",
		"packages/acme-web/e2e/checkout.e2e.ts",
		"packages/acme-web/specs/_util/test-setup.ts",
		"packages/acme-web/specs-it/acceptance/onboarding.it.ts",
		"test/core/ripple.test.ts",
		"tests/helpers/make-run.ts",
		"packages/acme-web/src/__tests__/total.ts",
		"packages/acme-web/src/__mocks__/stripe.ts",
		"packages/acme-web/test/fixtures/run.ts",
		"packages/acme-web/src/fixtures/make-run.ts",
		"packages/acme-web/vitest.setup.ts",
		"jest.setup.js",
		"packages/acme-web/src/setupTests.ts",
	])
		expect(kind(f), f).toBe("test");
});

it("classifies application code as production under the default globs", () => {
	const kind = rippleClassifier(defaults);
	for (const f of [
		"packages/acme-web/src/invoices/total.ts",
		"packages/acme-web/src/server/repositories/run.ts",
		"src/core/config.ts",
		"packages/acme-web/src/testimonials/card.tsx",
		"packages/acme-web/src/lib/latest.ts",
		"README.md",
	])
		expect(kind(f), f).toBe("production");
});

it("marks nothing as generated by default, and generated globs win over test globs", () => {
	expect(rippleClassifier(defaults)("packages/db/generated/client.ts")).toBe(
		"production",
	);
	const kind = rippleClassifier({
		tests: [...DEFAULT_TEST_GLOBS],
		generated: ["packages/db/generated/**", "**/*.gen.ts"],
	});
	expect(kind("packages/db/generated/client.ts")).toBe("generated");
	expect(kind("packages/acme-web/test/schema.gen.ts")).toBe("generated");
	expect(kind("packages/acme-web/test/schema.ts")).toBe("test");
});

it("with no test globs, every file that is not generated is production", () => {
	expect(rippleClassifier({ tests: [], generated: [] })("src/a.test.ts")).toBe(
		"production",
	);
});

it("classifies a list of files in order, each with its kind", () => {
	expect(
		classifyRipples(["src/a.ts", "src/a.test.ts", ".storybook/x.gen.ts"], {
			tests: [...DEFAULT_TEST_GLOBS],
			generated: ["**/*.gen.ts"],
		}),
	).toEqual([
		{ file: "src/a.ts", kind: "production" },
		{ file: "src/a.test.ts", kind: "test" },
		{ file: ".storybook/x.gen.ts", kind: "generated" },
	]);
});

it("the profile's ripple option defaults to the common test globs and no generated globs", () => {
	expect(testProfile().ripple).toEqual({
		tests: [...DEFAULT_TEST_GLOBS],
		generated: [],
	});
});

it("the profile's ripple option takes its own globs, each list defaulting on its own", () => {
	const base = { ...testProfile() } as Record<string, unknown>;
	delete base.ripple;
	const p = ProfileSchema.parse({
		...base,
		ripple: { generated: ["packages/db/generated/**"] },
	});
	expect(p.ripple).toEqual({
		tests: [...DEFAULT_TEST_GLOBS],
		generated: ["packages/db/generated/**"],
	});
	expect(
		ProfileSchema.parse({ ...base, ripple: { tests: ["**/*.check.ts"] } })
			.ripple,
	).toEqual({ tests: ["**/*.check.ts"], generated: [] });
});

it("the profile rejects a misspelt ripple key", () => {
	const r = ProfileSchema.safeParse({
		...testProfile(),
		ripple: { test: ["**/*.test.ts"] },
	});
	expect(r.success).toBe(false);
});
